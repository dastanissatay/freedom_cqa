"""Маскирование персональных данных перед отправкой транскрипта в LLM.

В интерфейсе и в базе транскрипт хранится как есть; маскируется только текст промпта.
Метка сохраняет факт наличия данных (важно для критериев «Идентификация» и «Грубые ошибки»),
но не сами значения. Регулярные выражения — эвристика: кодовые слова, ФИО и адреса не ловятся.
"""
from __future__ import annotations

import re

# порядок важен: сначала длинные и специфичные шаблоны
_RULES: list[tuple[str, re.Pattern]] = [
    ("[EMAIL]", re.compile(r"\b[\w.+-]+@[\w-]+\.[\w.-]+\b")),
    ("[IBAN]", re.compile(r"\b[A-Z]{2}\d{2}(?:\s?[A-Z0-9]{4}){3,7}(?:\s?[A-Z0-9]{1,4})?\b")),
    ("[КАРТА]", re.compile(r"(?<!\d)(?:\d{4}[ -]?){3}\d{4}(?:[ -]?\d{1,3})?(?!\d)")),
    ("[ТЕЛЕФОН]", re.compile(r"(?<![\w+])(?:\+?[78]|\+\d{3})[\s(-]*\d{3}[\s)-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}(?!\d)")),
    ("[ИИН]", re.compile(r"(?<!\d)\d{12}(?!\d)")),
    ("[НОМЕР]", re.compile(r"(?<!\d)\d{8,11}(?!\d)")),  # счёт/договор и прочие длинные номера
]


def mask(text: str) -> str:
    for label, rx in _RULES:
        text = rx.sub(label, text)
    return text


def found(text: str) -> list[str]:
    """Какие типы данных нашлись (для отладки/статистики)."""
    return [label for label, rx in _RULES if rx.search(text)]
